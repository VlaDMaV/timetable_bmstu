def group_display_name(name: str) -> str:
    """Показывает новые группы по-русски, даже если их ещё нет в словаре."""
    stored = (name or "").strip()
    if stored in groups:
        return groups[stored]

    normalized = stored.lower()
    if normalized.startswith("uik"):
        normalized = "ИУК" + normalized[3:]
    elif normalized.startswith("mk"):
        normalized = "МК" + normalized[2:]
    else:
        return stored
    return normalized.translate(str.maketrans({"b": "Б", "m": "М", "a": "А"}))


