DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM semester_group_renames WHERE group_id IS NULL) THEN
        RAISE EXCEPTION 'Some source groups are missing: %',
            (SELECT string_agg(old_name, ', ' ORDER BY old_name)
             FROM semester_group_renames WHERE group_id IS NULL);
    END IF;

    IF EXISTS (
        SELECT 1
        FROM semester_group_renames r
        JOIN groups g ON g.name = lower(
            replace(replace(replace(replace(replace(
                r.new_name, 'ИУК', 'uik'), 'МК', 'mk'), 'Б', 'b'), 'М', 'm'), 'А', 'a')
        ) AND g.id <> r.group_id
    ) THEN
        RAISE EXCEPTION 'Target group names already exist: %',
            (SELECT string_agg(r.new_name, ', ' ORDER BY r.new_name)
             FROM semester_group_renames r
             JOIN groups g ON g.name = lower(
                replace(replace(replace(replace(replace(
                    r.new_name, 'ИУК', 'uik'), 'МК', 'mk'), 'Б', 'b'), 'М', 'm'), 'А', 'a')
             ) AND g.id <> r.group_id);
    END IF;
END $$;

